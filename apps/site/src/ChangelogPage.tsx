function formatDate(d: string) {
  const [y, m, day] = d.split("-").map(Number);
  const month = new Date(Date.UTC(y, m - 1, 1)).toLocaleString("en-GB", { month: "long", timeZone: "UTC" });
  return day ? `${day} ${month} ${y}` : `${month} ${y}`;
}
